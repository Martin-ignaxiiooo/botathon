-- V004 · calc.* (planificación, escenarios, cuadratura) y audit.log. Idempotente.
CREATE TABLE IF NOT EXISTS calc.plan_mes (
    persona_id        bigint NOT NULL,
    it                int NOT NULL,
    mes               smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
    periodo           text NOT NULL CHECK (periodo IN ('ene_abr', 'may_dic')),
    horas_contratadas numeric,
    horas_dir         numeric,
    horas_ind         numeric,
    horas_nas         numeric,
    pct_dir_final     numeric,
    pct_ind_final     numeric,
    ate_dir_semana    int,
    ate_ind_semana    int,
    semanas_habiles   numeric,
    ate_dir           int,
    ate_dir_ind       int,
    meta              int,
    foja              numeric,
    version_param     int,
    calculado_en      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (persona_id, it, mes)
);
CREATE INDEX IF NOT EXISTS plan_mes_it_idx ON calc.plan_mes (it, mes);

CREATE TABLE IF NOT EXISTS calc.escenario (
    escenario_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         text NOT NULL,
    descripcion    text,
    cambios        jsonb NOT NULL DEFAULT '{}'::jsonb,   -- cambios de parámetros a simular
    estado         text NOT NULL DEFAULT 'borrador' CHECK (estado IN ('borrador', 'simulado', 'aprobado', 'descartado')),
    version_base   int,
    version_creada int,
    creado_por     text NOT NULL DEFAULT current_user,
    creado_en      timestamptz NOT NULL DEFAULT now(),
    aprobado_en    timestamptz
);

-- Misma forma que calc.plan_mes + escenario_id
CREATE TABLE IF NOT EXISTS calc.plan_mes_escenario (
    escenario_id bigint NOT NULL REFERENCES calc.escenario ON DELETE CASCADE,
    LIKE calc.plan_mes INCLUDING DEFAULTS INCLUDING CONSTRAINTS,
    PRIMARY KEY (escenario_id, persona_id, it, mes)
);

CREATE TABLE IF NOT EXISTS calc.cuadratura (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_id   bigint NOT NULL,
    it           int,
    campo        text NOT NULL,
    mes          smallint,
    excel        numeric,
    sistema      numeric,
    diferencia   numeric,
    causa        text,
    calculado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS audit.log (
    log_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla         text NOT NULL,
    operacion     text NOT NULL,
    usuario       text NOT NULL DEFAULT current_user,
    motivo        text,
    antes         jsonb,
    despues       jsonb,
    registrado_en timestamptz NOT NULL DEFAULT clock_timestamp()
);
