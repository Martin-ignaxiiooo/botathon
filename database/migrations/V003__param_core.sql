-- V003 · param.* (reglas versionadas) y core.* (datos limpios). Idempotente.

-- ===== param =====
-- Una versión por carga de parámetros o escenario aplicado. Vigente = vigente_hasta IS NULL.
CREATE TABLE IF NOT EXISTS param.version (
    version       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carga_id      bigint REFERENCES stg.carga,
    escenario_id  bigint,
    descripcion   text,
    vigente_desde date NOT NULL DEFAULT current_date,
    vigente_hasta date,
    creada_por    text NOT NULL DEFAULT current_user,
    creada_en     timestamptz NOT NULL DEFAULT now()
);

-- Tablas de reglas: cada fila lleva su version y vigencia (copiadas de param.version).
CREATE TABLE IF NOT EXISTS param.cargo_distribucion (
    version       int NOT NULL REFERENCES param.version,
    vigente_desde date NOT NULL,
    vigente_hasta date,
    cod_esp       text,          -- viene vacío en 57 cargos del Excel
    cargo         text NOT NULL,
    unidad        text,
    min_directa   int,
    min_indirecta int,
    tramo         smallint NOT NULL CHECK (tramo IN (1, 2, 3)),
    pct_dir       numeric NOT NULL,
    pct_ind       numeric NOT NULL,
    pct_nas       numeric NOT NULL,
    PRIMARY KEY (version, cargo, tramo)
);

CREATE TABLE IF NOT EXISTS param.asignacion_catalogo (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 'tipo' se repite en el Excel
    version       int NOT NULL REFERENCES param.version,
    vigente_desde date NOT NULL,
    vigente_hasta date,
    tipo          text NOT NULL,
    horas_semana  numeric,
    requiere_dmn  boolean,
    descripcion   text
);
CREATE INDEX IF NOT EXISTS asignacion_catalogo_version_idx ON param.asignacion_catalogo (version, tipo);

CREATE TABLE IF NOT EXISTS param.calendario_mes (
    version       int NOT NULL REFERENCES param.version,
    vigente_desde date NOT NULL,
    vigente_hasta date,
    mes           smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
    zona          text NOT NULL DEFAULT 'general',
    dias          int,
    inhabiles     int,
    dias_habiles  int,
    semanas       numeric NOT NULL,
    PRIMARY KEY (version, mes, zona)
);

CREATE TABLE IF NOT EXISTS param.grupal (
    version         int NOT NULL REFERENCES param.version,
    vigente_desde   date NOT NULL,
    vigente_hasta   date,
    cod_esp         text NOT NULL,
    grupo_it        text NOT NULL CHECK (grupo_it IN ('San-Con', 'otros')),
    pct_grupal      numeric,
    pacientes_grupo numeric,
    PRIMARY KEY (version, cod_esp, grupo_it)
);

-- Constantes de negocio (meta 0.9, jornadas 44/42, etc.). Seed en B-03.
CREATE TABLE IF NOT EXISTS param.general (
    version       int NOT NULL REFERENCES param.version,
    vigente_desde date NOT NULL,
    vigente_hasta date,
    clave         text NOT NULL,
    valor         numeric NOT NULL,
    descripcion   text,
    PRIMARY KEY (version, clave)
);

-- Catálogos (no versionados)
CREATE TABLE IF NOT EXISTS param.instituto (
    it              int PRIMARY KEY,
    nombre          text NOT NULL,
    zona            text NOT NULL DEFAULT 'general' CHECK (zona IN ('general', 'arica', 'nuble', 'aysen')),
    grupo_it        text NOT NULL DEFAULT 'otros' CHECK (grupo_it IN ('San-Con', 'otros')),
    correo_jefatura text
);

CREATE TABLE IF NOT EXISTS param.cargo_homologado (
    cargo_origen text PRIMARY KEY,   -- cargo tal como viene en el BUK
    cargo        text NOT NULL,      -- cargo de param.cargo_distribucion
    cod_esp      text,
    dudoso       boolean NOT NULL DEFAULT false,
    nota         text
);

-- ===== core =====
CREATE TABLE IF NOT EXISTS core.persona (
    persona_id      bigint PRIMARY KEY,   -- único identificador (sin nombres ni RUT)
    primera_carga   bigint REFERENCES stg.carga,
    ultima_carga    bigint REFERENCES stg.carga,
    creada_en       timestamptz NOT NULL DEFAULT now(),
    actualizada_en  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS core.dotacion_mes (
    persona_id      bigint NOT NULL REFERENCES core.persona,
    it              int NOT NULL,
    mes             smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
    periodo         date,
    instituto       text,
    area            text,
    sub_area        text,
    centro_costo    text,
    tipo_contrato   text,
    tipo_trabajador text,
    fecha_ingreso   date,
    fecha_termino   date,
    horas_semanales numeric NOT NULL,
    cargo_origen    text,                 -- cargo del BUK
    cargo           text,                 -- cargo homologado
    cod_esp         text,
    dias_semana     smallint,
    origen          text NOT NULL DEFAULT 'buk' CHECK (origen IN ('buk', 'proyectado')),
    carga_id        bigint REFERENCES stg.carga,
    actualizado_en  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (persona_id, it, mes)
);
CREATE INDEX IF NOT EXISTS dotacion_mes_it_idx ON core.dotacion_mes (it, mes);

CREATE TABLE IF NOT EXISTS core.asignacion (
    asignacion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_id    bigint NOT NULL,
    it            int NOT NULL,
    tipo          text NOT NULL,
    horas         numeric NOT NULL,
    desde         date,
    hasta         date,
    solicitante   text,
    motivo        text,
    estado        text NOT NULL DEFAULT 'vigente',
    carga_id      bigint REFERENCES stg.carga,
    creada_en     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS asignacion_persona_idx ON core.asignacion (persona_id, it);

CREATE TABLE IF NOT EXISTS core.excepcion_multi_it (
    persona_id bigint NOT NULL,
    it         int NOT NULL,
    mes        smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
    horas      numeric NOT NULL,
    carga_id   bigint REFERENCES stg.carga,
    PRIMARY KEY (persona_id, it, mes)
);

CREATE TABLE IF NOT EXISTS core.cambios (
    cambio_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carga_id       bigint NOT NULL REFERENCES stg.carga,
    carga_anterior bigint REFERENCES stg.carga,
    tipo           text NOT NULL CHECK (tipo IN ('alta', 'baja', 'cambio_jornada', 'cambio_cargo', 'cambio_it', 'cambio_vigencia')),
    persona_id     bigint NOT NULL,
    it             int,
    mes_vigencia   int,
    antes          jsonb,
    despues        jsonb,
    detectado_en   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS cambios_carga_idx ON core.cambios (carga_id);

CREATE TABLE IF NOT EXISTS core.alerta (
    alerta_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carga_id   bigint REFERENCES stg.carga,
    tipo       text NOT NULL,      -- p. ej. 'cargo_sin_homologar', 'multi_it_excede'
    persona_id bigint,
    it         int,
    mes        smallint,
    detalle    jsonb,
    creada_en  timestamptz NOT NULL DEFAULT now()
);
